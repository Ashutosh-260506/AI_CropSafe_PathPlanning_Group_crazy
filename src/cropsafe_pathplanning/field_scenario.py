"""Shared field scenario for the AI-CropSafe Path Planning project.

This module is Hitesh's (Member 1) primary deliverable.  It exposes:

- ``FIELD_CONFIG``  — a plain dictionary describing every parameter of the demo
  field, usable by any module without importing the full ``Field`` dataclass.
- ``make_field_map()``  — constructs the ``FieldMap`` object used by the BFS /
  DFS / GBFS modules (``types.py`` interface).
- ``make_field()``  — constructs the ``Field`` dataclass used by the unified
  search and replanning modules (``model.py`` interface).
- ``print_field_ascii()``  — prints a labelled ASCII map to stdout for quick
  visual verification.

Loading the scenario
--------------------
Any module in the project can get the shared configuration with::

    from cropsafe_pathplanning.field_scenario import (
        FIELD_CONFIG,
        make_field,
        make_field_map,
        print_field_ascii,
    )

Both ``make_field()`` and ``make_field_map()`` read from ``FIELD_CONFIG`` so
the single source of truth is never duplicated.

Coordinate convention
---------------------
Every position is a ``(row, col)`` tuple with 0-based indexing.
Rows increase **downward**; columns increase **rightward**.

Movement rules
--------------
Four-directional (cardinal) movement only: UP (-1,0), DOWN (+1,0),
LEFT (0,-1), RIGHT (0,+1).  Diagonal steps are **not** permitted.
This is confirmed by ``Field.neighbors()`` and ``FieldMap.get_neighbors()``.

Cost model
----------
- Base step cost:          1.0  (every legal move)
- Risk surcharge:          +2.0 (entering a cell orthogonally adjacent to any
                                  protected cell)
- Blocked cell entry:      ∞    (illegal; never generated by neighbors())

Formal problem summary
----------------------
- Initial state : (6, 1)
- Goal state    : (6, 16)
- State space   : all (row, col) with 0 ≤ row < 12, 0 ≤ col < 18, not blocked
- Actions       : {UP, DOWN, LEFT, RIGHT} subject to bounds + not-blocked
- Transition    : deterministic; (r,c) + action → (r±1, c) or (r, c±1)
- Goal test     : state == (6, 16)
- Path cost     : Σ step_cost(cell) for each cell entered after the start
"""

from __future__ import annotations

from typing import Any

# ---------------------------------------------------------------------------
# Single source of truth for the shared 12 × 18 demo field
# ---------------------------------------------------------------------------

FIELD_CONFIG: dict[str, Any] = {
    # Grid dimensions
    "height": 12,
    "width": 18,
    # Robot start and goal (row, col)
    "start": (6, 1),
    "goal": (6, 16),
    # Crop rows — visual annotation; used for colour-coding in SVG output.
    # Robot must NOT enter these cells.
    # Band A: row 3, cols 1–16
    # Band B: row 8, cols 1–16
    "crop_rows": frozenset(
        (r, c) for r in (3, 8) for c in range(1, 17)
    ),
    # Protected cells — subset of crop_rows and blocked. Adjacent traversable
    # cells receive a proximity penalty.
    # Band A: row 3, cols 2–15
    # Band B: row 8, cols 2–15
    "protected": frozenset(
        (r, c) for r in (3, 8) for c in range(2, 16)
    ),
    # Known static obstacles — pre-mapped; always blocked from the start.
    # Two symmetric pillar pairs flanking the direct route.
    "obstacles": frozenset({(5, 5), (6, 5), (5, 12), (6, 12)}),
    # Risk surcharge applied when entering a cell adjacent to any protected cell.
    # Must be ≥ 0 to preserve admissibility of the Manhattan heuristic.
    "risk_penalty": 2.0,
    # Hidden obstacle (online experiment only).
    # Absent from the robot's initial known map; discovered at runtime.
    "hidden_obstacle": (10, 9),
}


# ---------------------------------------------------------------------------
# Factory helpers
# ---------------------------------------------------------------------------

def make_field():  # type: ignore[return]
    """Return a ``Field`` dataclass populated from ``FIELD_CONFIG``.

    Use this with the A*, evaluation, and replanning modules.

    Returns
    -------
    model.Field
        The 12 × 18 demo field ready for A*, BFS, DFS, or Greedy search.
    """
    from cropsafe_pathplanning.model import Field

    cfg = FIELD_CONFIG
    return Field(
        height=cfg["height"],
        width=cfg["width"],
        start=cfg["start"],
        goal=cfg["goal"],
        crop_rows=set(cfg["crop_rows"]),
        protected=set(cfg["protected"]),
        obstacles=set(cfg["obstacles"]),
        risk_penalty=cfg["risk_penalty"],
    )


def make_field_map():
    """Return a ``FieldMap`` object populated from ``FIELD_CONFIG``.

    Use this with the BFS / DFS (``bfs_dfs.py``) and GBFS (``gbfs.py``)
    modules that consume the ``types.FieldMap`` interface.

    Returns
    -------
    types.FieldMap
        The 12 × 18 demo field with protected cells and obstacles blocked.
    """
    from cropsafe_pathplanning.types import FieldMap

    cfg = FIELD_CONFIG
    blocked = set(cfg["crop_rows"]) | set(cfg["protected"]) | set(cfg["obstacles"])
    return FieldMap(
        height=cfg["height"],
        width=cfg["width"],
        blocked_cells=blocked,
    )


def make_field_map_with_hidden():
    """Return a ``FieldMap`` that includes the hidden obstacle as blocked.

    Use this to construct the *true* map (as opposed to the robot's known map)
    for the online replanning experiment.

    Returns
    -------
    types.FieldMap
    """
    from cropsafe_pathplanning.types import FieldMap

    cfg = FIELD_CONFIG
    blocked = set(cfg["crop_rows"]) | set(cfg["protected"]) | set(cfg["obstacles"]) | {cfg["hidden_obstacle"]}
    return FieldMap(
        height=cfg["height"],
        width=cfg["width"],
        blocked_cells=blocked,
    )


