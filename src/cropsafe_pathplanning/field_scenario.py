# ASCII visualisation
# ---------------------------------------------------------------------------

# Symbol legend
_SYMBOLS: dict[str, str] = {
    "safe": ".",
    "crop": "C",
    "protected": "P",
    "obstacle": "X",
    "hidden": "H",
    "start": "S",
    "goal": "G",
    "path": "*",
    "expanded": "·",
}

SYMBOL_LEGEND: str = """\
Symbol legend
  .  Safe ground (traversable, base cost 1.0)
  C  Crop row edge (blocked — robot must not enter)
  P  Protected buffer (blocked — safety margin around crop row)
  X  Known static obstacle (blocked)
  H  Hidden obstacle (not in robot's initial map; blocked in true map)
  S  Start position  (6, 1)
  G  Goal  position  (6, 16)
  *  Planned path cell (shown at runtime)
  ·  Expanded / visited node during search (shown at runtime)
"""


def render_ascii(
    *,
    show_hidden: bool = True,
    path: list[tuple[int, int]] | None = None,
    expanded: list[tuple[int, int]] | None = None,
) -> str:
    """Return a labelled ASCII string of the demo field.

    Parameters
    ----------
    show_hidden:
        If *True*, mark the hidden obstacle with ``H``.  Set *False* to show
        the robot's initial view (the hidden cell appears as ``.``).
    path:
        Optional list of ``(row, col)`` positions to mark with ``*``.
    expanded:
        Optional list of ``(row, col)`` positions to mark with ``·``.

    Returns
    -------
    str
        Multi-line string ready to be printed.
    """
    cfg = FIELD_CONFIG
    h, w = cfg["height"], cfg["width"]
    protected: frozenset[tuple[int, int]] = cfg["protected"]
    crop_rows: frozenset[tuple[int, int]] = cfg["crop_rows"]
    obstacles: frozenset[tuple[int, int]] = cfg["obstacles"]
    hidden: tuple[int, int] = cfg["hidden_obstacle"]
    start: tuple[int, int] = cfg["start"]
    goal: tuple[int, int] = cfg["goal"]

    path_set = set(path or [])
    expanded_set = set(expanded or [])

    lines: list[str] = []
    # Column header
    col_hdr = "     " + " ".join(f"{c:2d}" for c in range(w))
    lines.append(col_hdr)
    lines.append("   +" + "---" * w + "+")

    for r in range(h):
        row_chars: list[str] = []
        for c in range(w):
            pos = (r, c)
            if pos == start:
                ch = " S "
            elif pos == goal:
                ch = " G "
            elif pos in protected:
                ch = " P "
            elif pos in crop_rows:
                ch = " C "
            elif pos in obstacles:
                ch = " X "
            elif show_hidden and pos == hidden:
                ch = " H "
            elif pos in path_set:
                ch = " * "
            elif pos in expanded_set:
                ch = " · "
            else:
                ch = " . "
            row_chars.append(ch)
        lines.append(f"{r:2d} |" + "".join(row_chars) + "|")

    lines.append("   +" + "---" * w + "+")
    return "\n".join(lines)


def print_field_ascii(**kwargs: Any) -> None:
    """Print the demo field ASCII map to stdout.

    Accepts the same keyword arguments as :func:`render_ascii`.
    """
    print(render_ascii(**kwargs))
    print()
    print(SYMBOL_LEGEND)


